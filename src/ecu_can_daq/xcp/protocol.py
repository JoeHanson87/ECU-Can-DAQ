"""XCP protocol constants and commands."""
from __future__ import annotations


class XcpCommands:
    CONNECT = 0xFF
    DISCONNECT = 0xFE
    GET_STATUS = 0xFD
    SYNCH = 0xFC
    GET_COMM_MODE_INFO = 0xFB
    GET_ID = 0xFA
    SET_REQUEST = 0xF9
    GET_SEED = 0xF8
    UNLOCK = 0xF7
    SET_MTA = 0xF6
    UPLOAD = 0xF5
    SHORT_UPLOAD = 0xF4
    BUILD_CHECKSUM = 0xF3
    TRANSPORT_LAYER_CMD = 0xF2
    USER_CMD = 0xF1

    DOWNLOAD = 0xF0
    DOWNLOAD_NEXT = 0xEF
    DOWNLOAD_MAX = 0xEE
    SHORT_DOWNLOAD = 0xED
    MODIFY_BITS = 0xEC

    # DAQ
    SET_DAQ_PTR = 0xE2
    WRITE_DAQ = 0xE1
    SET_DAQ_LIST_MODE = 0xE0
    GET_DAQ_LIST_MODE = 0xDF
    START_STOP_DAQ_LIST = 0xDE
    START_STOP_SYNCH = 0xDD
    GET_DAQ_CLOCK = 0xDC
    READ_DAQ = 0xDB
    GET_DAQ_PROCESSOR_INFO = 0xDA
    GET_DAQ_RESOLUTION_INFO = 0xD9
    GET_DAQ_LIST_INFO = 0xD8
    GET_DAQ_EVENT_INFO = 0xD7
    FREE_DAQ = 0xD6
    ALLOC_DAQ = 0xD5
    ALLOC_ODT = 0xD4
    ALLOC_ODT_ENTRY = 0xD3

    # PGM
    PROGRAM_CLEAR = 0xD0
    PROGRAM = 0xCF
    PROGRAM_RESET = 0xCE
    GET_PGM_PROCESSOR_INFO = 0xCD
    GET_SECTOR_INFO = 0xCC
    PROGRAM_PREPARE = 0xCB
    PROGRAM_FORMAT = 0xCA
    PROGRAM_NEXT = 0xC9
    PROGRAM_MAX = 0xC8
    PROGRAM_VERIFY = 0xC7

    # Cal page
    GET_PAGE_INFO = 0xBE if False else 0x78  # placeholder
    POSITIVE = 0xFF
    NEGATIVE = 0xFE

    # Common responses
    POSITIVE_RESPONSE = 0xFF
    NEGATIVE_RESPONSE = 0xFE

# Backward compat aliases
POSITIVE_RESPONSE = XcpCommands.POSITIVE_RESPONSE
NEGATIVE_RESPONSE = XcpCommands.NEGATIVE_RESPONSE
CONNECT = XcpCommands.CONNECT
DISCONNECT = XcpCommands.DISCONNECT
SET_MTA = XcpCommands.SET_MTA
UPLOAD = XcpCommands.UPLOAD
DOWNLOAD = XcpCommands.DOWNLOAD
SHORT_DOWNLOAD = XcpCommands.SHORT_DOWNLOAD
GET_STATUS = XcpCommands.GET_STATUS
GET_COMM_MODE_INFO = XcpCommands.GET_COMM_MODE_INFO
GET_DAQ_CLOCK = XcpCommands.GET_DAQ_CLOCK
START_STOP_DAQ_LIST = XcpCommands.START_STOP_DAQ_LIST
START_STOP_SYNCH = XcpCommands.START_STOP_SYNCH
SET_DAQ_PTR = XcpCommands.SET_DAQ_PTR
WRITE_DAQ = XcpCommands.WRITE_DAQ
SET_DAQ_LIST_MODE = XcpCommands.SET_DAQ_LIST_MODE
GET_DAQ_PROCESSOR_INFO = XcpCommands.GET_DAQ_PROCESSOR_INFO
GET_DAQ_RESOLUTION_INFO = XcpCommands.GET_DAQ_RESOLUTION_INFO
