"""PAR/DCM import/export scaffold."""
from __future__ import annotations

from pathlib import Path
from typing import Any
import re


class ParParser:
    """Very small PAR file parser (VALUE/CURVE etc)."""

    @staticmethod
    def load(path: Path) -> dict[str, Any]:
        text = path.read_text(encoding="utf-8", errors="ignore")
        # Naive parse: NAME value;
        pattern = re.compile(r'^\s*(\w+)\s+([0-9.\-eE+]+|".*?"|\{.*?\})', re.MULTILINE)
        result = {}
        for m in pattern.finditer(text):
            result[m.group(1)] = m.group(2)
        return result

    @staticmethod
    def save(path: Path, data: dict[str, Any]) -> None:
        lines = ['/* PAR file generated by ECU-Can-DAQ */']
        for name, val in data.items():
            lines.append(f"{name} {val};")
        path.write_text("\n".join(lines), encoding="utf-8")


class DcmParser:
    """DCM file similar to PAR but with more metadata – stub."""

    @staticmethod
    def load(path: Path) -> dict[str, Any]:
        return ParParser.load(path)

    @staticmethod
    def save(path: Path, data: dict[str, Any]) -> None:
        ParParser.save(path, data)
